const mongoose = require('mongoose');

const userSchema = new mongoose.Schema({
    fullName: {
        type: String,
        required: true
    },
    username: {
        type: String,
        required: true,
        unique: true
    },
    password: {
        type: String,
        required: true,
        minlength: 6
    },
    profilePic: {
        type: String,
        default: ""
    }
}, { timestamps: true }); // timestamps automatically adds createdAt and updatedAt fields

const User = mongoose.model('User', userSchema);

module.exports = User;